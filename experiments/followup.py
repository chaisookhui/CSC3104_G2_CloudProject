"""Sequential follow-up cohort using the existing trace/compare and study CLIs.

No resets until the read-only preservation export has verified successfully.
Existing completed attempts are retained; interrupted attempts require a new prefix.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import control

from runtime import ROOT, RESULTS, utc, write_json
from workloads import make_trace


def planned(prefix,skip_hpa=False):
    jobs=[]
    for target in (() if skip_hpa else ('api','worker')):
        for repeat in (1,2):
            jobs.append((f'24-{target}-r{repeat}', ['experiments/study.py','--case',f'24-{target}','--reset-lab']))
    for scenario in ('F2','F3','F6'):
        trace=ROOT/'.local/traces'/prefix/(scenario+'-42.json')
        jobs.append(('18-'+scenario,['experiments/run.py','compare','--trace',str(trace),
            '--reset-lab','--hold-ttl','120','--replicas','1','--repeats','1','--seeds','10']))
    jobs.append(('23-grid',['experiments/study.py','--case','capacity','--reset-lab',
        '--rates','200','250','300','--allow-high-rate-lab','--repeats','1']))
    jobs.append(('19-bursts',['experiments/study.py','--case','19','--reset-lab',
        '--peaks','100','150','200','--repeats','3']))
    return jobs


def boundary_trials(grid):
    """Two additional independent trials at each initially observed boundary."""
    jobs=[]
    for replicas in (1,2,4):
        valid=[r for r in grid if r['replicas']==replicas and r.get('timing_fidelity')
               and r.get('scheduled')==r.get('offered')==r.get('launched') and r.get('generator_dropped')==0]
        passing=[r['rate'] for r in valid if r.get('sustainable')]
        missing=[r['rate'] for r in valid if not r.get('sustainable')]
        rates=sorted(set(([max(passing)] if passing else [])+([min(missing)] if missing else [])))
        for rate in rates:
            jobs.append((f'23-boundary-n{replicas}-rate{rate}',
                ['experiments/study.py','--case','capacity','--reset-lab','--rates',str(rate),
                 '--replicas',str(replicas),'--repeats','2','--allow-high-rate-lab']))
    return jobs


def verify_recorded(arguments, manifest):
    recorded=manifest.get('arguments') or manifest.get('commands',[{}])[-1].get('arguments',{})
    index=1
    while index<len(arguments):
        flag=arguments[index]
        if not flag.startswith('--'):
            index+=1;continue
        key=flag[2:].replace('-','_')
        end=index+1
        while end<len(arguments) and not arguments[end].startswith('--'):end+=1
        values=arguments[index+1:end]
        actual=recorded.get(key)
        expected=values if isinstance(actual,list) else values[0] if values else True
        if (list(map(str,actual)) if isinstance(actual,list) else str(actual)) != (
                list(map(str,expected)) if isinstance(expected,list) else str(expected)):
            raise ValueError('Existing completed run conditions differ: '+key)
        index=end


@control.controlled_main(deployed=False, driver=True)
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prefix',required=True)
    parser.add_argument('--preserved',required=True,help='Verified preserve_lab.py run ID')
    parser.add_argument('--plan-only',action='store_true')
    parser.add_argument('--skip-hpa',action='store_true',help='Run remaining scheduler/capacity/burst studies; retain separately completed HPA cycles')
    parser.add_argument('--resume',action='store_true')
    args=parser.parse_args()
    # Validate run ID before using it as a path component, without creating runs.
    import re
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]{0,65}',args.prefix):parser.error('Invalid short cohort prefix')
    output=ROOT/'output/validation'/args.prefix
    output.mkdir(parents=True,exist_ok=True)
    jobs=planned(args.prefix,args.skip_hpa)
    for scenario in ('F2','F3','F6'):
        # Use the public trace CLI for the seed-42 input; all ten traces are
        # generated by compare from that exact unmodified trace.
        path=ROOT/'.local/traces'/args.prefix/(scenario+'-42.json')
        path.parent.mkdir(parents=True,exist_ok=True)
        if not path.exists():
            subprocess.run([sys.executable,'experiments/run.py','trace','--scenario',scenario,
                '--seed','42','--count','40','--batch-size','10','--output',str(path)],cwd=ROOT,check=True)
        if json.loads(path.read_text())!=make_trace(scenario,40,42,10):raise ValueError('Existing trace differs')
    write_json(output/'plan.json',dict(created_at=utc(),namespace='csc3104-lab',preserved=args.preserved,
        commands=[[sys.executable,*cmd,'--run',args.prefix+'-'+name] for name,cmd in jobs],
        adaptive='After the 200/250/300 grid, two extra fresh trials at each replica count\'s highest passing tested rate and first valid miss. Invalid delivery is retained and diagnosed before interpreting capacity.'))
    if args.plan_only:
        print(output/'plan.json');return 0
    preserved=RESULTS/args.preserved
    if json.loads((preserved/'summary.json').read_text())['status']!='PASS':raise ValueError('Verified lab export required')
    expected=json.loads((preserved/'summary.json').read_text())['archive_sha256']
    if hashlib.sha256((preserved/'prior-evidence.zip').read_bytes()).hexdigest()!=expected:
        raise ValueError('Preservation archive hash mismatch')
    attempts=json.loads((output/'attempts.json').read_text()) if (output/'attempts.json').exists() else []
    def execute(name,arguments):
        run=args.prefix+'-'+name
        directory=RESULTS/run
        summary=directory/('comparison.json' if 'compare' in arguments else 'summary.json')
        command=[sys.executable,*arguments,'--run',run]
        record=dict(run=run,command=command,started_at=utc())
        if directory.exists() and any(p.name!='.control' for p in directory.iterdir()):
            manifest=json.loads((directory/'run.json').read_text())
            verify_recorded(arguments+['--run',run],manifest)
            command.append('--resume')
        with (output/(name+'.log')).open('a',encoding='utf-8') as log:
            write_json(output/(name+'-command.json'),record)
            record['exit_code']=control.child_call(command,cwd=ROOT,stdout=log,stderr=subprocess.STDOUT)
        if not summary.exists():
            raise RuntimeError('Child stopped without completed evidence; no next job started: '+run)
        record['finished_at']=utc()
        record['status']=json.loads(summary.read_text())['status'] if summary.exists() else 'INTERRUPTED'
        record['evidence']=str(directory.relative_to(ROOT))
        attempts.append(record);write_json(output/'attempts.json',attempts)
        print(run,record['status'],flush=True)
    for name,command in jobs:
        execute(name,command)
        if name=='23-grid':
            grid=RESULTS/(args.prefix+'-'+name)/'summary.json'
            if grid.exists():
                for child,cmd in boundary_trials(json.loads(grid.read_text())['results']):execute(child,cmd)
    write_json(output/'execution.json',dict(finished_at=utc(),attempts=attempts,
        interpretation='Attempt statuses preserve original workload meanings. Article synthesis evaluates capacity SLO separately.'))
    return 0


if __name__=='__main__':sys.exit(main())
